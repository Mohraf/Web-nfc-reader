// Generates js/crypto/curves.js from OpenSSL's explicit curve parameters.
// Run: node tools/gen-curves.mjs  (requires openssl on PATH)
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const CURVES = [
  // [PACE standardized domain parameter id, openssl name, display name, OID of named curve]
  [8, 'prime192v1', 'NIST P-192', '1.2.840.10045.3.1.1'],
  [9, 'brainpoolP192r1', 'brainpoolP192r1', '1.3.36.3.3.2.8.1.1.3'],
  [10, 'secp224r1', 'NIST P-224', '1.3.132.0.33'],
  [11, 'brainpoolP224r1', 'brainpoolP224r1', '1.3.36.3.3.2.8.1.1.5'],
  [12, 'prime256v1', 'NIST P-256', '1.2.840.10045.3.1.7'],
  [13, 'brainpoolP256r1', 'brainpoolP256r1', '1.3.36.3.3.2.8.1.1.7'],
  [14, 'brainpoolP320r1', 'brainpoolP320r1', '1.3.36.3.3.2.8.1.1.9'],
  [15, 'secp384r1', 'NIST P-384', '1.3.132.0.34'],
  [16, 'brainpoolP384r1', 'brainpoolP384r1', '1.3.36.3.3.2.8.1.1.11'],
  [17, 'brainpoolP512r1', 'brainpoolP512r1', '1.3.36.3.3.2.8.1.1.13'],
  [18, 'secp521r1', 'NIST P-521', '1.3.132.0.35'],
];

function parse(buf, off = 0) {
  const tag = buf[off]; let len = buf[off + 1]; let p = off + 2;
  if (len & 0x80) { const n = len & 0x7f; len = 0; for (let i = 0; i < n; i++) len = len * 256 + buf[p++]; }
  return { tag, start: p, end: p + len, value: buf.subarray(p, p + len) };
}
function children(node, buf) { const out = []; let p = node.start; while (p < node.end) { const c = parse(buf, p); out.push(c); p = c.end; } return out; }
const hex = (b) => Buffer.from(b).toString('hex');
const int = (b) => { let h = hex(b).replace(/^(00)+(?=..)/, ''); return h; };

let out = '// AUTO-GENERATED by tools/gen-curves.mjs from OpenSSL explicit parameters. Do not edit.\n';
out += '// Keys are PACE standardized domain parameter IDs (BSI TR-03110 / ICAO 9303 Part 11, table 6).\n';
out += 'export const CURVES = {\n';
for (const [id, name, display, oid] of CURVES) {
  const der = execFileSync('openssl', ['ecparam', '-name', name, '-param_enc', 'explicit', '-outform', 'DER']);
  const root = parse(der); const [, fieldID, curve, base, order, cofactor] = children(root, der);
  const p = int(children(fieldID, der)[1].value);
  const [a, b] = children(curve, der).map((c) => int(c.value));
  const g = hex(base.value); if (!g.startsWith('04')) throw new Error('compressed base');
  const fl = (g.length - 2) / 2;
  out += `  ${id}: { name: '${display}', oid: '${oid}', size: ${Math.ceil(p.length / 2)},\n` +
    `    p: 0x${p}n,\n    a: 0x${a.replace(/^(00)+(?=..)/, '')}n,\n    b: 0x${b.replace(/^(00)+(?=..)/, '')}n,\n` +
    `    gx: 0x${g.slice(2, 2 + fl)}n,\n    gy: 0x${g.slice(2 + fl)}n,\n` +
    `    n: 0x${int(order.value)}n, h: ${parseInt(int(cofactor.value), 16)}n },\n`;
}
out += '};\n\nexport function curveByOid(oid) {\n  return Object.values(CURVES).find((c) => c.oid === oid) || null;\n}\n';
writeFileSync(new URL('../js/crypto/curves.js', import.meta.url), out);
console.log('wrote js/crypto/curves.js');
