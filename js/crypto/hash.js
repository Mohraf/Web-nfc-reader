// Hash helpers on top of WebCrypto (available in browsers on https and in Node >= 19).
const NAMES = { 'SHA-1': 'SHA-1', 'SHA-224': null, 'SHA-256': 'SHA-256', 'SHA-384': 'SHA-384', 'SHA-512': 'SHA-512' };

export async function digest(alg, data) {
  if (alg === 'SHA-224') return sha224(data);
  const name = NAMES[alg];
  if (!name) throw new Error('unsupported hash ' + alg);
  return new Uint8Array(await globalThis.crypto.subtle.digest(name, data));
}
export const sha1 = (d) => digest('SHA-1', d);
export const sha256 = (d) => digest('SHA-256', d);

